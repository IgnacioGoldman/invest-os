const { chromium } = require('../../frontend/node_modules/playwright-core');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('file://' + path.join(__dirname, 'runs/2026-10-25/ranking.html'));
    assert.equal(await page.locator('tbody tr').count(), 200);
    assert.equal(await page.locator('thead th').count(), 9);
    assert.equal(await page.getByRole('columnheader', { name: 'Red flags', exact: true }).count(), 1);
    assert.equal(await page.getByRole('columnheader', { name: 'Green flags', exact: true }).count(), 1);
    assert.equal(await page.locator('td.red-flags').count(), 200);
    assert.equal(await page.locator('td.green-flags').count(), 200);
    assert.equal(await page.locator('td.support').count(), 200);
    assert.equal(await page.locator('tbody tr:visible').count(), 64);
    assert.equal(await page.locator('tbody tr:visible').first().locator('td strong').first().textContent(), 'ANIP');
    await page.locator('#financial-filter').selectOption('pass');
    assert.equal(await page.locator('tbody tr:visible').count(), 33);
    await page.locator('#financial-filter').selectOption('fail');
    assert.equal(await page.locator('tbody tr:visible').count(), 31);
    assert.equal(await page.locator('tbody tr:visible').first().locator('td strong').first().textContent(), 'BMY');
    assert.match(await page.locator('tbody tr:visible').first().locator('.financial').textContent(), /Operating margin: 31\.03%/);
    assert.match(await page.locator('#financial-refresh').textContent(), /185 available, 15 Unknown/);
    assert.equal(await page.locator('tbody tr:visible').first().locator('.financial .reason').textContent(), 'Red flags: incomplete assessment');
    assert.equal(await page.getByText('Operating margin: unavailable or unvalidated', { exact: true }).count(), 0);
    await page.locator('#financial-filter').selectOption('all');
    await page.locator('#support-only').uncheck();
    assert.equal(await page.locator('tbody tr:visible').count(), 200);
    assert.equal(await page.locator('tbody tr').first().locator('.support-above').textContent(), 'Above Support');
    const anip = page.locator('tbody tr').filter({ has: page.locator('td strong', { hasText: /^ANIP$/ }) });
    assert.equal(await anip.locator('.support-at').textContent(), 'At Support');
    assert.equal(await anip.locator('.green-flags > strong').textContent(), '2');
    assert.equal(await anip.locator('.red-flags > strong').textContent(), '0');
    assert.match(await anip.locator('.green-flags .flag-names').textContent(), /Sustained revenue growth/);
    await anip.locator('.green-flags summary').click();
    assert.ok(await anip.locator('.green-flags details[open]').count());
    assert.match(await anip.locator('.green-flags details').textContent(), /Revenue YoY growth ≥ 8%/);
    await anip.locator('.green-flags summary').click();
    assert.ok(await page.locator('.red-flags > strong', { hasText: 'Not fully assessed' }).count() > 0);
    assert.ok(await page.locator('.green-flags > strong', { hasText: '≥' }).count() > 0);
    await page.locator('#search').fill('ADBE');
    assert.equal(await page.locator('tbody tr:visible').count(), 1);
    await page.locator('#search').fill('Unknown');
    assert.ok(await page.locator('tbody tr:visible').count() > 0);
    await page.locator('#search').fill('');
    await page.locator('#support-only').check();
    await page.screenshot({ path: '/private/tmp/invest-universe-1280.png' });
    assert.deepEqual(errors, []);
    console.log('Browser verified: separate red/green columns for all 200 stocks, counts and rule details, default 64 supported stocks, 33 passing / 31 excluded, and search.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
